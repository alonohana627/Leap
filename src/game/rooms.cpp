std::vector<RoomDef> _all()
{
    std::vector<RoomDef> all = _foothills();
    for (auto world : {_cliffs(), _quarry(), _foundry()}) {
        for (RoomDef& room : world) {
            all.push_back(std::move(room));
        }
    }
    all.push_back(_summit());
    return all;
}

